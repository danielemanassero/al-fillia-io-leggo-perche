-- Schema per il progetto "#ioleggoperché"
-- Da eseguire una sola volta nell'SQL Editor del progetto Supabase.

create table if not exists books (
  id bigint generated by default as identity primary key,
  title text not null,
  status text not null default 'disponibile' check (status in ('disponibile', 'acquistato')),
  created_at timestamptz not null default now()
);

-- Una volta acquistato, il libro non può più essere modificato in alcun modo
-- (né lo stato né il titolo), indipendentemente da chi esegue la richiesta.
create or replace function prevent_purchased_update()
returns trigger as $$
begin
  if old.status = 'acquistato' then
    raise exception 'Libro già acquistato: non può più essere modificato';
  end if;
  return new;
end;
$$ language plpgsql;

drop trigger if exists trg_prevent_purchased_update on books;
create trigger trg_prevent_purchased_update
  before update on books
  for each row
  execute function prevent_purchased_update();

-- Row Level Security: l'app usa la anon key pubblica, quindi i permessi
-- vengono definiti qui, lato database.
alter table books enable row level security;

drop policy if exists "books_select_all" on books;
create policy "books_select_all" on books
  for select
  using (true);

drop policy if exists "books_insert_all" on books;
create policy "books_insert_all" on books
  for insert
  with check (true);

-- Si può aggiornare solo un libro ancora "disponibile", e solo per portarlo
-- ad "acquistato" (mai il percorso inverso). Nessuna policy di delete:
-- le cancellazioni sono sempre negate.
drop policy if exists "books_update_mark_purchased" on books;
create policy "books_update_mark_purchased" on books
  for update
  using (status = 'disponibile')
  with check (status = 'acquistato');

